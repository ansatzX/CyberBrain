#!/usr/bin/env node

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const repoRoot = resolve(dirname(scriptPath), "..");
const pluginRoot = join(repoRoot, "plugins", "awesome-agent-select");
const profileDir = join(pluginRoot, "agent-profiles");
const codexDir = join(pluginRoot, "agents");
const piAgentsDir = join(repoRoot, "pi", "subagents", "awesome-agent-select");
const generatedHeader = "# Generated by tools/generate-agent-adapters.mjs; do not edit directly.\n";
const piPackage = "cyberbrain";
const args = new Set(process.argv.slice(2));

if ([...args].some((arg) => arg !== "--check" && arg !== "--bootstrap-from-codex")) {
	throw new Error("Usage: node tools/generate-agent-adapters.mjs [--check] [--bootstrap-from-codex]");
}
if (args.has("--check") && args.has("--bootstrap-from-codex")) {
	throw new Error("--check cannot be combined with --bootstrap-from-codex.");
}

function filesIn(directory, suffix) {
	if (!existsSync(directory)) return [];
	return readdirSync(directory, { withFileTypes: true })
		.filter((entry) => entry.isFile() && entry.name.endsWith(suffix))
		.map((entry) => entry.name)
		.sort();
}

function ensureSafeName(name, filePath) {
	if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
		throw new Error(`Invalid agent name '${name}' derived from ${relative(repoRoot, filePath)}.`);
	}
}

function parseProfile(filePath) {
	const raw = readFileSync(filePath, "utf8").replace(/\r\n/g, "\n");
	const normalized = raw.endsWith("\n") ? raw.slice(0, -1) : raw;
	const separator = normalized.indexOf("\n\n");
	if (separator <= 0) {
		throw new Error(`${relative(repoRoot, filePath)} must contain a description paragraph followed by a blank line and instructions.`);
	}
	const description = normalized.slice(0, separator).trim().replace(/\s+/g, " ");
	const instructions = normalized.slice(separator + 2).trim();
	if (!description || !instructions) {
		throw new Error(`${relative(repoRoot, filePath)} must contain both a description and instructions.`);
	}
	if (instructions.includes("'''")) {
		throw new Error(`${relative(repoRoot, filePath)} instructions cannot contain ''' because generated Codex TOML uses a literal multiline string.`);
	}
	return { description, instructions };
}

function renderCodex(name, profilePath, { description, instructions }) {
	return `${generatedHeader}# Source: ${relative(repoRoot, profilePath)}\nname = ${JSON.stringify(name)}\ndescription = ${JSON.stringify(description)}\ndeveloper_instructions = '''\n${instructions}\n'''\n`;
}

function renderPi(name, profilePath, { description, instructions }) {
	return `---\nname: ${name}\npackage: ${piPackage}\ndescription: ${JSON.stringify(description)}\nsystemPromptMode: replace\ninheritProjectContext: true\ninheritSkills: true\ndefaultContext: fresh\ngeneratedFrom: ${relative(repoRoot, profilePath)}\n---\n\n${instructions}\n`;
}

function expectedOutputs() {
	const profileNames = filesIn(profileDir, ".md");
	if (profileNames.length === 0) throw new Error(`No canonical role profiles found in ${relative(repoRoot, profileDir)}.`);
	return profileNames.map((filename) => {
		const name = filename.slice(0, -".md".length);
		const profilePath = join(profileDir, filename);
		ensureSafeName(name, profilePath);
		const profile = parseProfile(profilePath);
		return {
			codexPath: join(codexDir, `${name}.toml`),
			codexContent: renderCodex(name, profilePath, profile),
			piPath: join(piAgentsDir, `${name}.md`),
			piContent: renderPi(name, profilePath, profile),
		};
	});
}

function bootstrapProfiles() {
	if (existsSync(profileDir) && filesIn(profileDir, ".md").length > 0) {
		throw new Error(`Refusing bootstrap: ${relative(repoRoot, profileDir)} already contains profile sources.`);
	}
	const tomlFiles = filesIn(codexDir, ".toml");
	if (tomlFiles.length === 0) throw new Error(`No Codex TOMLs found in ${relative(repoRoot, codexDir)}.`);
	mkdirSync(profileDir, { recursive: true });
	for (const filename of tomlFiles) {
		const filePath = join(codexDir, filename);
		const raw = readFileSync(filePath, "utf8").replace(/\r\n/g, "\n");
		const name = filename.slice(0, -".toml".length);
		ensureSafeName(name, filePath);
		const match = raw.match(/^name = (.+)\ndescription = (.+)\n(?:\n)?developer_instructions = '''\n([\s\S]*?)\n'''\n?$/);
		if (!match) throw new Error(`Cannot bootstrap ${relative(repoRoot, filePath)}: expected the current three-field TOML layout.`);
		const declaredName = JSON.parse(match[1]);
		const description = JSON.parse(match[2]);
		if (declaredName !== name) throw new Error(`${relative(repoRoot, filePath)} filename and name disagree.`);
		if (typeof description !== "string" || !description.trim()) throw new Error(`${relative(repoRoot, filePath)} has an invalid description.`);
		const instructions = match[3].trim();
		if (!instructions) throw new Error(`${relative(repoRoot, filePath)} has empty developer instructions.`);
		writeFileSync(join(profileDir, `${name}.md`), `${description}\n\n${instructions}\n`);
	}
	console.log(`Bootstrapped ${tomlFiles.length} canonical role profiles in ${relative(repoRoot, profileDir)}.`);
}

function reconcileDirectory(directory, expected, suffix, check) {
	const expectedByPath = new Map(expected.map((entry) => [entry.path, entry.content]));
	const actualPaths = filesIn(directory, suffix).map((filename) => join(directory, filename));
	const issues = [];
	for (const [filePath, content] of expectedByPath) {
		if (!existsSync(filePath)) {
			issues.push(`Missing generated file: ${relative(repoRoot, filePath)}`);
		} else if (readFileSync(filePath, "utf8") !== content) {
			issues.push(`Stale generated file: ${relative(repoRoot, filePath)}`);
		}
	}
	for (const filePath of actualPaths) {
		if (!expectedByPath.has(filePath)) issues.push(`Unexpected generated file: ${relative(repoRoot, filePath)}`);
	}
	if (check) return issues;
	if (issues.some((issue) => issue.startsWith("Unexpected"))) {
		for (const filePath of actualPaths) {
			if (expectedByPath.has(filePath)) continue;
			const content = readFileSync(filePath, "utf8");
			if (!content.startsWith(generatedHeader)) {
				throw new Error(`Refusing to remove unmanaged file: ${relative(repoRoot, filePath)}`);
			}
			rmSync(filePath);
		}
	}
	mkdirSync(directory, { recursive: true });
	for (const [filePath, content] of expectedByPath) writeFileSync(filePath, content);
	return [];
}

if (args.has("--bootstrap-from-codex")) bootstrapProfiles();

const outputs = expectedOutputs();
const codexIssues = reconcileDirectory(codexDir, outputs.map(({ codexPath: path, codexContent: content }) => ({ path, content })), ".toml", args.has("--check"));
const piIssues = reconcileDirectory(piAgentsDir, outputs.map(({ piPath: path, piContent: content }) => ({ path, content })), ".md", args.has("--check"));
const issues = [...codexIssues, ...piIssues];
if (issues.length > 0) {
	for (const issue of issues) console.error(issue);
	process.exitCode = 1;
} else if (args.has("--check")) {
	console.log(`Agent adapters are current for ${outputs.length} role profiles.`);
} else {
	console.log(`Generated Codex and Pi adapters for ${outputs.length} role profiles.`);
}
